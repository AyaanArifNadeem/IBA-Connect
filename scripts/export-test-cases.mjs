#!/usr/bin/env node
/**
 * Export docs/testing/test-cases.json to:
 *   - docs/testing/generated/test-cases.tex   (included by test-cases.tex and test-results.tex)
 *   - docs/build/testing/IBA_Connect_Test_Cases.xlsx  (course template layout, columns B-L from row 2)
 *
 * Also checks the cases: unique IDs, Positive/Negative only, Pass/Fail only, and at least one
 * positive and one negative case for every requirement in SCOPE (course rule).
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import ExcelJS from "exceljs";

const root = resolve(import.meta.dirname, "..");
const source = join(root, "docs/testing/test-cases.json");
const texOut = join(root, "docs/testing/generated/test-cases.tex");
const xlsxOut = join(root, "docs/build/testing/IBA_Connect_Test_Cases.xlsx");

/** Requirements in scope for the current sprint. */
const SCOPE = [
  ...Array.from({ length: 10 }, (_, i) => `FR1.${i + 1}`),
  "FR2.1", "FR2.2", "FR2.3",
  ...Array.from({ length: 8 }, (_, i) => `FR3.${i + 1}`),
  ...Array.from({ length: 5 }, (_, i) => `FR4.${i + 1}`),
];

const { cases } = JSON.parse(readFileSync(source, "utf8"));

// ------------------------------------------------------------------ checks
const problems = [];
const ids = new Set();
for (const c of cases) {
  if (!/^TC-\d{3}$/.test(c.id)) problems.push(`${c.id}: id must look like TC-001`);
  if (ids.has(c.id)) problems.push(`${c.id}: duplicate id`);
  ids.add(c.id);
  if (!["Positive", "Negative"].includes(c.type)) problems.push(`${c.id}: type must be Positive or Negative`);
  if (!["", "Pass", "Fail"].includes(c.result)) problems.push(`${c.id}: result must be empty, Pass or Fail`);
  if (c.result && !c.actual) problems.push(`${c.id}: a result needs an actual output`);
  for (const field of ["req", "feature", "scenario", "pre", "data", "expected"]) {
    if (!c[field]) problems.push(`${c.id}: missing ${field}`);
  }
  if (!Array.isArray(c.steps) || c.steps.length === 0) problems.push(`${c.id}: needs at least one step`);
}
for (const req of SCOPE) {
  const forReq = cases.filter((c) => c.req === req);
  if (!forReq.some((c) => c.type === "Positive")) problems.push(`${req}: no positive test case`);
  if (!forReq.some((c) => c.type === "Negative")) problems.push(`${req}: no negative test case`);
}
if (problems.length) {
  console.error("Test case problems:\n  " + problems.join("\n  "));
  process.exit(1);
}

// Sort by requirement (FR1.2 before FR1.10, FRs before NFRs), then by id
const reqKey = (r) => {
  const m = /^(N?FR)(\d+)(?:\.(\d+))?/.exec(r) ?? [];
  return [m[1] === "NFR" ? 1 : 0, Number(m[2] ?? 0), Number(m[3] ?? 0)];
};
const ordered = [...cases].sort((a, b) => {
  const [x, y] = [reqKey(a.req), reqKey(b.req)];
  for (let i = 0; i < 3; i++) if (x[i] !== y[i]) return x[i] - y[i];
  return a.id.localeCompare(b.id);
});

// ------------------------------------------------------------------- LaTeX
const tex = (s) =>
  String(s)
    .replace(/\\/g, "\\textbackslash{}")
    .replace(/([&%$#_{}])/g, "\\$1")
    .replace(/~/g, "\\textasciitilde{}")
    .replace(/\^/g, "\\textasciicircum{}")
    .replace(/"([^"]*)"/g, "``$1''")
    .replace(/\//g, "/\\allowbreak{}");
/** Let long emails and identifiers wrap inside narrow columns. */
const breakable = (s) => s.replace(/([@.])/g, "$1\\allowbreak{}");
const steps = (list) => list.map((s, i) => `${i + 1}.~${tex(s)}`).join("\\newline ");

// Full rows (course template columns) and a short results view
const fullRows = ordered.map(
  (c) =>
    [c.id, tex(c.req), tex(c.feature), tex(c.scenario), c.type, tex(c.pre), steps(c.steps), breakable(tex(c.data)), tex(c.expected), tex(c.actual), c.result].join(" & ") +
    "\\\\\\midrule",
);
const resultRows = ordered.map(
  (c) => [c.id, tex(c.req), tex(c.scenario), tex(c.actual), c.result].join(" & ") + "\\\\\\midrule",
);
const total = cases.length;
const passed = cases.filter((c) => c.result === "Pass").length;
const failed = cases.filter((c) => c.result === "Fail").length;
mkdirSync(dirname(texOut), { recursive: true });
writeFileSync(
  texOut,
  [
    "% Generated by scripts/export-test-cases.mjs from test-cases.json. Do not edit by hand.",
    `\\def\\tctotal{${total}}\\def\\tcpassed{${passed}}\\def\\tcfailed{${failed}}\\def\\tcnotrun{${total - passed - failed}}`,
    `\\def\\tcpositive{${cases.filter((c) => c.type === "Positive").length}}\\def\\tcnegative{${cases.filter((c) => c.type === "Negative").length}}`,
    "\\def\\tcrowsfull{%",
    ...fullRows.map((r) => r + "%"),
    "}",
    "\\def\\tcrowsresults{%",
    ...resultRows.map((r) => r + "%"),
    "}",
    "",
  ].join("\n"),
);

// -------------------------------------------------------------------- xlsx
const wb = new ExcelJS.Workbook();
wb.creator = "IBA Connect";
const ws = wb.addWorksheet("Sheet1");
const headers = [
  "Test Case No", "Requirement No.", "Feature Name", "Scenario / Description", "Positive / Negative",
  "Pre-Condition", "Steps", "Test Data", "Expected Output", "Actual Output", "Pass / Fail",
];
const widths = [11.7, 15, 14, 34, 12, 24, 40, 20, 30, 24, 9];
widths.forEach((w, i) => (ws.getColumn(i + 2).width = w));
ws.getColumn(1).width = 4;
const header = ws.getRow(2);
headers.forEach((h, i) => {
  const cell = header.getCell(i + 2);
  cell.value = h;
  cell.font = { bold: true, name: "Calibri", size: 11 };
  cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FFF2F2F2" } };
});
ordered.forEach((c, n) => {
  const row = ws.getRow(n + 3);
  [
    c.id, c.req, c.feature, c.scenario, c.type, c.pre,
    c.steps.map((s, i) => `${i + 1}- ${s}`).join("\n"),
    c.data, c.expected, c.actual, c.result,
  ].forEach((v, i) => (row.getCell(i + 2).value = v));
});
const thin = { style: "thin", color: { argb: "FFBFBFBF" } };
for (let r = 2; r <= ordered.length + 2; r++) {
  for (let col = 2; col <= 12; col++) {
    const cell = ws.getRow(r).getCell(col);
    cell.alignment = { wrapText: true, vertical: "top" };
    cell.border = { top: thin, left: thin, bottom: thin, right: thin };
    if (!cell.font?.bold) cell.font = { name: "Calibri", size: 11 };
  }
}
ws.views = [{ state: "frozen", ySplit: 2 }];
mkdirSync(dirname(xlsxOut), { recursive: true });
await wb.xlsx.writeFile(xlsxOut);

console.log(`${total} test cases (${passed} pass, ${failed} fail, ${total - passed - failed} not run)`);
console.log(`  ${texOut.replace(root + "\\", "").replace(root + "/", "")}`);
console.log(`  ${xlsxOut.replace(root + "\\", "").replace(root + "/", "")}`);
