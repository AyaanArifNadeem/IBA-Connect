#!/usr/bin/env node
/**
 * Entity relationship diagram generated from prisma/schema.prisma, so the ERD in the
 * architecture document always matches the database (kickoff section 7).
 *
 *   node scripts/erd.mjs          write docs/architecture/erd.dot and docs/architecture/erd.pdf
 *   node scripts/erd.mjs --check  exit 1 if erd.dot is out of date (used by the unit test)
 *
 * Layout: Graphviz (WebAssembly, no install needed). PDF: Playwright's Chromium.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const schemaPath = join(root, "prisma/schema.prisma");
const dotPath = join(root, "docs/architecture/erd.dot");
const pdfPath = join(root, "docs/architecture/erd.pdf");

/** Read models, fields and relations from the Prisma schema (enough for an ERD). */
export function parseSchema(text) {
  const enums = new Set([...text.matchAll(/^enum (\w+) \{/gm)].map((m) => m[1]));
  const models = [];
  for (const m of text.matchAll(/^model (\w+) \{([\s\S]*?)^\}/gm)) {
    const [, name, body] = m;
    const fields = [];
    const blockIds = [];
    for (const raw of body.split("\n")) {
      const line = raw.replace(/\/\/.*$/, "").trim();
      if (!line) continue;
      const blockId = line.match(/^@@id\(\[([^\]]+)\]/);
      if (blockId) blockIds.push(...blockId[1].split(",").map((s) => s.trim()));
      if (line.startsWith("@@")) continue;
      const f = line.match(/^(\w+)\s+(\w+)(\[\])?(\?)?\s*(.*)$/);
      if (!f) continue;
      const [, fname, type, list, optional, attrs] = f;
      const rel = attrs.match(/@relation\([^)]*fields:\s*\[([^\]]+)\]/);
      fields.push({
        name: fname,
        type,
        list: Boolean(list),
        optional: Boolean(optional),
        id: /@id\b/.test(attrs),
        unique: /@unique\b/.test(attrs),
        relationFields: rel ? rel[1].split(",").map((s) => s.trim()) : null,
      });
    }
    fields.forEach((f) => (f.id ||= blockIds.includes(f.name)));
    models.push({ name, fields });
  }
  const modelNames = new Set(models.map((m) => m.name));
  for (const model of models) {
    for (const f of model.fields) f.isRelation = modelNames.has(f.type);
    const fks = new Set(model.fields.flatMap((f) => f.relationFields ?? []));
    for (const f of model.fields) f.fk = fks.has(f.name);
  }
  return { models, enums };
}

const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

/** Graphviz DOT: one table per model, crow's-foot-style edges for each foreign key. */
export function toDot({ models }) {
  const lines = [
    "// Generated by scripts/erd.mjs from prisma/schema.prisma. Do not edit by hand.",
    "digraph ERD {",
    '  graph [rankdir=LR, splines=true, overlap=false, nodesep=0.35, ranksep=0.9, fontname="Helvetica", bgcolor="white"];',
    '  node [shape=plaintext, fontname="Helvetica", fontsize=10];',
    '  edge [fontname="Helvetica", fontsize=9, color="#6B7280", arrowsize=0.7];',
  ];
  for (const model of models) {
    const rows = model.fields
      .filter((f) => !f.isRelation)
      .map((f) => {
        const keys = [f.id ? "PK" : "", f.fk ? "FK" : "", f.unique && !f.id ? "UQ" : ""].filter(Boolean).join(",");
        const type = `${f.type}${f.optional ? "?" : ""}`;
        return `<TR><TD ALIGN="LEFT" PORT="${f.name}">${f.id ? "<B>" : ""}${esc(f.name)}${f.id ? "</B>" : ""}</TD><TD ALIGN="LEFT"><FONT COLOR="#6B7280">${esc(type)}</FONT></TD><TD ALIGN="LEFT">${keys ? `<FONT COLOR="#000000">${keys}</FONT>` : " "}</TD></TR>`;
      })
      .join("");
    lines.push(
      `  ${model.name} [label=<<TABLE BORDER="1" CELLBORDER="0" CELLSPACING="0" CELLPADDING="3" COLOR="#9CA3AF"><TR><TD COLSPAN="3" BGCOLOR="#000000"><FONT COLOR="white"><B>${model.name}</B></FONT></TD></TR>${rows}</TABLE>>];`,
    );
  }
  for (const model of models) {
    for (const f of model.fields) {
      if (!f.isRelation || !f.relationFields) continue;
      const fkFields = f.relationFields.map((n) => model.fields.find((x) => x.name === n));
      const oneToOne = fkFields.length === 1 && fkFields[0]?.unique;
      const label = `${f.name} (${oneToOne ? "1:1" : "N:1"})`;
      lines.push(
        `  ${model.name} -> ${f.type} [label="${label}", arrowhead=${oneToOne ? "teetee" : "tee"}, arrowtail=${oneToOne ? "teetee" : "crow"}, dir=both];`,
      );
    }
  }
  lines.push("}");
  return lines.join("\n") + "\n";
}

export function currentDot() {
  return toDot(parseSchema(readFileSync(schemaPath, "utf8")));
}

async function renderPdf(dot) {
  const { Graphviz } = await import("@hpcc-js/wasm-graphviz");
  const graphviz = await Graphviz.load();
  const svg = graphviz.dot(dot);
  const { chromium } = await import("@playwright/test");
  const browser = await chromium.launch();
  const page = await browser.newPage();
  // Scale the drawing to fit one A4 landscape page
  const fitted = svg.replace(/<svg width="[^"]*" height="[^"]*"/, '<svg width="100%" height="100%" preserveAspectRatio="xMidYMid meet"');
  await page.setContent(
    `<html><head><style>@page{size:A4 landscape;margin:8mm}html,body{margin:0;height:100%}svg{display:block;width:100%;height:100%}</style></head><body>${fitted}</body></html>`,
  );
  await page.pdf({ path: pdfPath, format: "A4", landscape: true, printBackground: true, pageRanges: "1", preferCSSPageSize: true });
  await browser.close();
}

if (import.meta.url === `file:///${process.argv[1].replace(/\\/g, "/")}` || process.argv[1]?.endsWith("erd.mjs")) {
  const dot = currentDot();
  if (process.argv.includes("--check")) {
    const saved = readFileSync(dotPath, "utf8");
    if (saved.replace(/\r\n/g, "\n") !== dot) {
      console.error("docs/architecture/erd.dot is out of date. Run: npm run docs:erd");
      process.exit(1);
    }
    console.log("ERD is up to date.");
  } else {
    writeFileSync(dotPath, dot);
    await renderPdf(dot);
    console.log("Wrote docs/architecture/erd.dot and erd.pdf");
  }
}
